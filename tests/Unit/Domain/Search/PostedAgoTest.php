<?php

declare(strict_types=1);

use App\Support\PostedAgo;
use Illuminate\Support\Carbon;

// Давность публикации на карточке: «2 ч назад», «вчера», «3 окт». Время в UTC, отображение — Europe/Moscow.

$now = Carbon::parse('2026-11-07 12:00:00', 'UTC');

it('форматирует давность по-русски', function (string $at, string $expected) use ($now) {
    expect(PostedAgo::format(Carbon::parse($at, 'UTC'), $now))->toBe($expected);
})->with([
    'только что' => ['2026-11-07 11:59:40', 'только что'],
    '5 минут' => ['2026-11-07 11:55:00', '5 мин назад'],
    '2 часа' => ['2026-11-07 10:00:00', '2 ч назад'],
    'вчера' => ['2026-11-06 07:00:00', 'вчера'],
    '2 дня' => ['2026-11-05 12:00:00', '2 дня назад'],
    '5 дней' => ['2026-11-02 12:00:00', '5 дней назад'],
    'неделя и больше — дата' => ['2026-10-03 12:00:00', '3 окт'],
    'прошлый год — с годом' => ['2025-12-24 12:00:00', '24 дек 2025'],
]);

it('меньше суток — часы, даже если календарная дата по Москве другая', function () use ($now) {
    expect(PostedAgo::format(Carbon::parse('2026-11-06 22:30:00', 'UTC'), $now))->toBe('14 ч назад');
});

it('время из будущего не ломает формат', function () use ($now) {
    expect(PostedAgo::format($now->copy()->addMinutes(3), $now))->toBe('только что');
});
