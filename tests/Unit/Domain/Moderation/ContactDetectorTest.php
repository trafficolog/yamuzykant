it('находит телефон, в том числе обходы', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Phone);
})->with('phones');

it('находит e-mail, в том числе обходы', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Email);
})->with('emails');

it('находит ссылки', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Link);
})->with('links');

it('находит мессенджеры, в том числе с подменой букв (режим «любое упоминание»)', function (string $text) {
    config(['moderation.messengers.block_mention_only' => true]);

    expect(contactOf($text))->toBe(ContactKind::Messenger);
})->with('messengers');

it('находит @-ники', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Handle);
})->with('handles');

it('не принимает за контакт год, модель, цену, дату и размеры', function (string $text) {
    expect(contactOf($text))->toBeNull();
})->with('clean');

it('возвращает вид, а маска прячет сам контакт', function (string $text, ContactKind $kind, string $masked) {
    $contact = (new ContactDetector)->find($text);

    expect($contact?->kind)->toBe($kind)->and($contact?->masked())->toBe($masked);
})->with([
    'телефон' => ['Звоните +7 (916) 123-45-67 после шести', ContactKind::Phone, '79*******67'],
    'почта' => ['пишите ivan.petrov@mail.ru', ContactKind::Email, 'i***@mail.ru'],
    'ссылка без пути' => ['смотрите https://example.com/lot/123?x=1', ContactKind::Link, 'example.com'],
    'ссылка без схемы' => ['t.me/ivan_guitar', ContactKind::Link, 't.me'],
    'ник' => ['мой ник @ivan_guitar', ContactKind::Handle, '@iv***'],
    'мессенджер — название как есть' => ['Пишите в WhatsApp ivan_g77', ContactKind::Messenger, 'whatsapp'],
]);

it('маска не длиннее 40 символов', function () {
    $contact = (new ContactDetector)->find('https://'.str_repeat('a', 80).'.com/path');

    expect(mb_strlen((string) $contact?->masked()))->toBeLessThanOrEqual(40);
});

it('берёт основы и сокращения мессенджеров из конфига', function () {
    config(['moderation.messengers.block_mention_only' => true, 'moderation.messengers.stems' => ['новыймесс'], 'moderation.messengers.abbreviations' => ['нм']]);

    expect(contactOf('пишите в новыймессе'))->toBe(ContactKind::Messenger)
        ->and(contactOf('мой нм'))->toBe(ContactKind::Messenger)
        ->and(contactOf('нмх рядом'))->toBeNull()
        ->and(contactOf('пишите в ватсап'))->toBeNull();
});

describe('режим «блокирует только название с номером или ником»', function () {
    beforeEach(function () {
        config(['moderation.messengers.block_mention_only' => false]);
    });

    it('голое упоминание не блокирует', function (string $text) {
        expect(contactOf($text))->toBeNull();
    })->with([
        'не пишу' => ['в WhatsApp не пишу'],
        'быстрее в телеграм' => ['ответ быстрее в телеграм'],
        'просто тг' => ['мой тг'],
        'цифра рядом' => ['WhatsApp 5 минут'],
    ]);

    it('название с ником, номером или @ блокирует', function (string $text, ContactKind $kind) {
        expect(contactOf($text))->toBe($kind);
    })->with([
        'tg и ник с подчёркиванием' => ['tg ivanov_g', ContactKind::Messenger],
        'вк с двоеточием' => ['вк: ivan', ContactKind::Messenger],
        'ig с двоеточием' => ['ig: ivan', ContactKind::Messenger],
        'название и номер' => ['WhatsApp 8 916 123 45 67', ContactKind::Phone],
        'название и @-ник' => ['Telegram @ivan_guitar', ContactKind::Handle],
        'название и длинный идентификатор' => ['skype ivan.guitar77', ContactKind::Messenger],
    ]);
});

it('режим по умолчанию — блокирует только мессенджер с номером, ником или идентификатором (решение OWNER, G1)', function () {
    expect(config('moderation.messengers.block_mention_only'))->toBeFalse()
        ->and(contactOf('в WhatsApp не пишу'))->toBeNull()
        ->and(contactOf('Телегу для кофра в комплекте'))->toBeNull()
        ->and(contactOf('пиши в лс'))->toBeNull()
        ->and(contactOf('в директ'))->toBeNull()
        ->and(contactOf('вайб есть'))->toBeNull()
        ->and(contactOf('tg ivanov_g'))->toBe(ContactKind::Messenger)
        ->and(contactOf('wh@tsapp ivan_g77'))->toBe(ContactKind::Messenger);
});

it('в режиме «любое упоминание» «Телегу для кофра» блокируется', function () {
    config(['moderation.messengers.block_mention_only' => true]);

    expect(contactOf('Телегу для кофра в комплекте'))->toBe(ContactKind::Messenger);
});

it('зона целиком на кириллице не приводится к латинице', function () {
    expect(contactOf("Состояние отличное.\u{0421}\u{043E}"))->toBeNull()
        ->and(contactOf("Гитара.\u{041C}\u{0435} нравится"))->toBeNull();
});

it('маска ссылки срезает userinfo', function (string $link, string $masked) {
    expect((new Contact(ContactKind::Link, $link))->masked())->toBe($masked);
})->with([
    'логин' => ['https://ivan@guitarshop.ru/lot', 'guitarshop.ru'],
    'логин и пароль' => ['http://ivan:secret@guitarshop.ru:8080/lot?x=1', 'guitarshop.ru:8080'],
    'без userinfo' => ['https://guitarshop.ru/lot', 'guitarshop.ru'],
]);

it('ссылка с userinfo всё равно блокируется', function () {
    expect(contactOf('смотрите https://ivan@guitarshop.ru/lot'))->not->toBeNull();
});
