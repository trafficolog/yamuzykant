it('находит телефон, в том числе обходы', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Phone);
})->with('phones');

it('находит e-mail, в том числе обходы', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Email);
})->with('emails');

it('находит ссылки', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Link);
})->with('links');

it('находит мессенджеры, в том числе с подменой букв', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Messenger);
})->with('messengers');

it('находит @-ники', function (string $text) {
    expect(contactOf($text))->toBe(ContactKind::Handle);
})->with('handles');

it('не принимает за контакт год, модель, цену, дату и размеры', function (string $text) {
    expect(contactOf($text))->toBeNull();
})->with('clean');

it('возвращает найденный фрагмент для пояснения модератору', function () {
    $contact = (new ContactDetector)->find('Звоните +7 (916) 123-45-67 после шести');

    expect($contact?->excerpt)->toContain('916');
});

it('берёт список мессенджеров из конфига', function () {
    config(['moderation.contacts.messengers' => ['новыймесс']]);

    expect(contactOf('пишите в новыймесс'))->toBe(ContactKind::Messenger)
        ->and(contactOf('пишите в ватсап'))->toBeNull();
});
