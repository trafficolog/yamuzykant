#!/usr/bin/env node
// ds-sync — копия дизайн-системы design/ds → resources/js/ds и генерация index.ts для алиаса @ds.
// Идемпотентен. Ручные правки в resources/js/ds будут перезаписаны.
import { readdirSync, statSync, mkdirSync, copyFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import { join, relative, dirname, extname, basename } from 'node:path';

const SRC = 'design/ds', DST = 'resources/js/ds';
const KEEP = new Set(['.js', '.jsx', '.ts', '.d.ts', '.css', '.json', '.woff', '.woff2', '.ttf', '.otf', '.svg']);
if (!existsSync(SRC)) { console.error(`нет ${SRC}`); process.exit(1); }
rmSync(DST, { recursive: true, force: true });

const copied = [];
const walk = d => { for (const n of readdirSync(d)) { const p = join(d, n); const s = statSync(p);
  if (s.isDirectory()) { if (!['docs', 'ui_kits'].includes(n)) walk(p); continue; }
  const ext = n.endsWith('.d.ts') ? '.d.ts' : extname(n);
  if (!KEEP.has(ext) || n.endsWith('.card.html')) continue;
  const out = join(DST, relative(SRC, p)); mkdirSync(dirname(out), { recursive: true }); copyFileSync(p, out); copied.push(relative(DST, out)); } };
walk(SRC);

const comps = copied.filter(f => f.startsWith('components') && f.endsWith('.jsx') && /^[A-Z]/.test(basename(f))).sort();
const index = `// AUTO-GENERATED by tools/ds-sync.mjs — не редактировать\n${comps.map(f => `export * from './${f.replace(/\\/g, '/').replace(/\.jsx$/, '')}';`).join('\n')}\n`;
writeFileSync(join(DST, 'index.ts'), index);
writeFileSync(join(DST, 'README.md'), '# Копия дизайн-системы\n\nНе редактировать. Источник — design/ds. Обновление: `npm run ds:sync` отдельным PR `chore(ds): sync`.\n');
console.log(`ds-sync: ${copied.length} файлов, ${comps.length} компонентов → ${DST}/index.ts`);
